"""Live microphone -> Whisper tiny.en -> Qwen2.5:1.5b, every 5 seconds.

Install in Python 3.12 venv:
    pip install faster-whisper sounddevice numpy requests
Start Ollama separately and pull qwen2.5:1.5b.
"""
import queue
import sys
import time

import numpy as np
import requests
import sounddevice as sd
from faster_whisper import WhisperModel

SAMPLE_RATE = 16000
CHUNK_SECONDS = 5
MODEL = "tiny.en"
OLLAMA_MODEL = "qwen2.5:1.5b"
OLLAMA_URL = "http://127.0.0.1:11434/api/chat"

SYSTEM_PROMPT = """
You are a speech transcription corrector.

You receive a short transcript generated by Whisper.

Your ONLY task is to correct obvious speech recognition mistakes.

RULES:
1. Correct misheard words using context.
2. Fix punctuation and capitalization.
3. Keep every word that is already correct.
4. Do not add new information.
5. Do not remove information.
6. Do not repeat previous sentences.
7. Do not summarize, paraphrase, or rewrite.
8. Do not combine the input with previous transcripts.
9. Output ONLY the corrected version of the NEW input.
10. If the input is already correct, return it unchanged.

The previous transcript, if provided, is CONTEXT ONLY.
Never include any previous transcript in your answer.
"""


def main():
    model = WhisperModel(MODEL, device="cpu", compute_type="int8")
    audio_queue = queue.Queue()
    pending = np.empty(0, dtype=np.float32)
    history = ""

    def on_audio(indata, frames, time_info, status):
        # Keep audio recording even while Whisper/Qwen are processing.
        audio_queue.put(indata[:, 0].copy())

    try:
        with sd.InputStream(samplerate=SAMPLE_RATE, channels=1, dtype="float32",
                            blocksize=1600, callback=on_audio):
            while True:
                pending = np.concatenate((pending, audio_queue.get()))
                while len(pending) >= SAMPLE_RATE * CHUNK_SECONDS:
                    chunk = pending[:SAMPLE_RATE * CHUNK_SECONDS]
                    pending = pending[SAMPLE_RATE * CHUNK_SECONDS:]

                    segments, _ = model.transcribe(
                        chunk, language="en", beam_size=1,
                        vad_filter=True, condition_on_previous_text=False,
                    )
                    raw = " ".join(s.text.strip() for s in segments).strip()
                    if not raw:
                        continue

                    prompt = (
                        "Correct only this Whisper transcription. "
                        "Output only the corrected text:\n\n"
                        f"{raw}"
                    )
                    try:
                        response = requests.post(
                            OLLAMA_URL,
                            json={
                                "model": OLLAMA_MODEL,
                                "stream": False,
                                "messages": [
                                    {"role": "system", "content": SYSTEM_PROMPT},
                                    {"role": "user", "content": prompt},
                                ],
                                "options": {"temperature": 0, "num_ctx": 2048,
                                            "num_predict": 150},
                            },
                            timeout=120,
                        )
                        response.raise_for_status()
                        corrected = response.json().get("message", {}).get("content", "").strip()
                    except (requests.RequestException, ValueError, KeyError) as exc:
                        print(f"Qwen error: {exc}", file=sys.stderr)
                        corrected = raw

                    if corrected:
                        # Only the corrected words are printed to stdout.
                        print(corrected, flush=True)
                        history = (history + " " + corrected).strip()
    except KeyboardInterrupt:
        pass
    except Exception as exc:
        print(f"Audio error: {exc}", file=sys.stderr)
        raise


if __name__ == "__main__":
    main()
